/**
 * Replace [data-lucide] placeholders with inline SVG.
 * Call once after each DOM update. Idempotent.
 */
export function refreshIcons() {
  if (typeof document === 'undefined') return;
  if (document.querySelector('[data-lucide]')) {
    createIcons({ icons: set, attrs: { 'stroke-width': 1.75 } });
  }
}

